CREATE TABLE IF NOT EXISTS system_errors (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, error_code VARCHAR(100) NOT NULL,
 path VARCHAR(255) NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX idx_errors_time(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS auth_attempts (
 email_hash CHAR(64) PRIMARY KEY, failures INT UNSIGNED NOT NULL DEFAULT 0,
 window_start DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
